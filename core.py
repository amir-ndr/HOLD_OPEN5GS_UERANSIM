#!/usr/bin/env python3
"""
Step 2a -- the Open5GS side: one real AMF / SMF / UPF process per tree node.

    python3 core.py start     # write configs, add subscribers, start the 80 NFs
    python3 core.py status    # what runs, what is registered, memory
    python3 core.py stop

The NFs run as plain user processes (no systemd, no CPU quota). The stock NRF,
SCP, UDM, UDR, AUSF, PCF, NSSF and BSF are reused. Run `sudo ./setup.sh` once
after every reboot: it stops the stock AMF/SMF/UPF and creates the UPF devices.

HOW ONE LEAF IS ADDRESSED (no slicing: a single S-NSSAI, sst 1)
    AMF   the gNB a UE attaches through is connected to exactly one AMF
    SMF   every AMF has its own tracking area, and an SMF registers for the
          tracking area of its parent AMF and for the DNNs of its own UPFs
    UPF   the DNN: d<smf><upf><a|b|c>, three DNNs per UPF so that one UE can
          hold up to three PDU sessions on the same leaf
"""
import json
import os
import signal
import subprocess
import sys
import tempfile
import time
import urllib.request

from tree import NODES, PLATFORMS, N_SMF, N_UPF, Node, of_kind

HERE = os.path.dirname(os.path.abspath(__file__))
CONF = os.path.join(HERE, "generated", "core")
LOGS = os.path.join(HERE, "logs", "core")

NRF = "http://127.0.0.10:7777"
SCP = "http://127.0.0.200:7777"
MCC, MNC = "999", "70"
BIN = {k: f"/usr/bin/open5gs-{k}d" for k in ("amf", "smf", "upf")}
STOCK = ("open5gs-amfd", "open5gs-smfd", "open5gs-upfd")   # must NOT run: they shadow ours

MAX_UE, MAX_PEER = 256, 256
SESSIONS = "abc"                    # up to three PDU sessions of one UE on one leaf
N_SUBSCRIBERS = 240
FIRST_MSIN = 700001
KEY = "465B5CE8B199B49FAA5F0A2EE238A6BC"
OPC = "E8ED289DEBA952E4283B54E88E6183CA"

GAUGE = {"amf": "ran_ue", "smf": "pfcp_sessions_active",
         "upf": "fivegs_upffunction_upf_sessionnbr"}
NFS = [x for x in NODES.values() if x.kind in BIN]


# ── addressing ───────────────────────────────────────────────────────────────
def name(x: Node) -> str:
    return x.id.replace(".", "-")


def addr(x: Node) -> str:
    host = {"amf": 10 + x.a,
            "smf": 20 + 3 * x.a + (x.k or 0),
            "upf": 40 + 6 * x.a + 2 * (x.k or 0) + (x.u or 0)}[x.kind]
    return f"127.0.{20 + x.n}.{host}"


def amf_index(x: Node) -> int:
    """0..7, one per AMF; also numbers its gNB pair."""
    return 2 * (x.n - 1) + x.a


def tac(x: Node) -> int:
    """Tracking area of the AMF subtree this node belongs to."""
    return 10 * x.n + x.a


def dnns(upf: Node) -> list[str]:
    return [f"d{upf.k}{upf.u}{s}" for s in SESSIONS]


def subnets(upf: Node) -> list[str]:
    second = 100 + 12 * (upf.n - 1) + 6 * upf.a + 2 * upf.k + upf.u
    return [f"10.{second}.{j}" for j in range(len(SESSIONS))]       # /24 each


def tun(upf: Node) -> str:
    return f"hf{upf.n}{upf.a}{upf.k}{upf.u}"


def leaf_type(sub: int) -> tuple[int, int]:
    """Subscriber -> the (SMF, UPF) position it can reach under any AMF."""
    return (sub % (N_SMF * N_UPF)) // N_UPF, sub % N_UPF


def imsi(sub: int) -> str:
    return f"{MCC}{MNC}{FIRST_MSIN + sub:010d}"


# ── configs ──────────────────────────────────────────────────────────────────
def head(x: Node) -> str:
    return f"""# {x.id}  -- generated by core.py
logger:
  file:
    path: {LOGS}/{name(x)}.log
global:
  max:
    ue: {MAX_UE}
    peer: {MAX_PEER}
"""


def amf_yaml(x: Node) -> str:
    return head(x) + f"""amf:
  sbi:
    server:
      - address: {addr(x)}
        port: 7777
    client:
      scp:
        - uri: {SCP}
  ngap:
    server:
      - address: {addr(x)}
  metrics:
    server:
      - address: {addr(x)}
        port: 9090
  guami:
    - plmn_id: {{ mcc: {MCC}, mnc: {MNC} }}
      amf_id: {{ region: 2, set: 1, pointer: {amf_index(x)} }}
  tai:
    - plmn_id: {{ mcc: {MCC}, mnc: {MNC} }}
      tac: {tac(x)}
  plmn_support:
    - plmn_id: {{ mcc: {MCC}, mnc: {MNC} }}
      s_nssai:
        - sst: 1
  security:
    integrity_order: [ NIA2, NIA1, NIA0 ]
    ciphering_order: [ NEA0, NEA1, NEA2 ]
  network_name:
    full: HOLD
  amf_name: {name(x)}
  time:
    t3512:
      value: 540
"""


def smf_yaml(x: Node) -> str:
    upfs = [NODES[c] for c in x.children]
    clients = "\n".join(f"        - address: {addr(u)}\n          dnn: [{', '.join(dnns(u))}]"
                        for u in upfs)
    pools = "\n".join(f"    - subnet: {net}.0/24\n      gateway: {net}.1\n      dnn: {d}"
                      for u in upfs for d, net in zip(dnns(u), subnets(u)))
    served = "\n".join(f"            - {d}" for u in upfs for d in dnns(u))
    return head(x) + f"""smf:
  sbi:
    server:
      - address: {addr(x)}
        port: 7777
    client:
      scp:
        - uri: {SCP}
  pfcp:
    server:
      - address: {addr(x)}
    client:
      upf:
{clients}
  gtpc:
    server:
      - address: {addr(x)}
  gtpu:
    server:
      - address: {addr(x)}
  metrics:
    server:
      - address: {addr(x)}
        port: 9090
  session:
{pools}
  dns:
    - 8.8.8.8
  mtu: 1400
  info:
    - s_nssai:
        - sst: 1
          dnn:
{served}
      tai:
        - plmn_id: {{ mcc: {MCC}, mnc: {MNC} }}
          tac: {tac(x)}
"""


def upf_yaml(x: Node) -> str:
    pools = "\n".join(f"    - subnet: {net}.0/24\n      gateway: {net}.1\n      dnn: {d}\n"
                      f"      dev: {tun(x)}" for d, net in zip(dnns(x), subnets(x)))
    return head(x) + f"""upf:
  pfcp:
    server:
      - address: {addr(x)}
  gtpu:
    server:
      - address: {addr(x)}
  metrics:
    server:
      - address: {addr(x)}
        port: 9090
  session:
{pools}
"""


def cfg(x: Node) -> str:
    return os.path.join(CONF, f"{name(x)}.yaml")


def generate() -> None:
    os.makedirs(CONF, exist_ok=True)
    os.makedirs(LOGS, exist_ok=True)
    make = {"amf": amf_yaml, "smf": smf_yaml, "upf": upf_yaml}
    for x in NFS:
        with open(cfg(x), "w") as f:
            f.write(make[x.kind](x))
    with open(os.path.join(HERE, "generated", "tun.conf"), "w") as f:   # read by setup.sh
        for x in of_kind("upf"):
            f.write(f"{tun(x)} {' '.join(net + '.1/24' for net in subnets(x))}\n")
    seen = [addr(x) for x in NFS] + [n for x in of_kind("upf") for n in subnets(x)]
    assert len(seen) == len(set(seen)), "address or subnet collision"


# ── subscribers ──────────────────────────────────────────────────────────────
def provision() -> str:
    ambr = {"downlink": {"value": 1, "unit": 3}, "uplink": {"value": 1, "unit": 3}}
    qos = {"index": 9, "arp": {"priority_level": 8, "pre_emption_capability": 1,
                               "pre_emption_vulnerability": 1}}
    docs = []
    for n in range(N_SUBSCRIBERS):
        k, u = leaf_type(n)
        docs.append({
            "imsi": imsi(n), "schema_version": 1, "msisdn": [],
            "imeisv": "4370816125816151", "mme_host": [], "mme_realm": [], "purge_flag": [],
            "access_restriction_data": 32, "subscriber_status": 0,
            "operator_determined_barring": 0, "network_access_mode": 0,
            "subscribed_rau_tau_timer": 12,
            "security": {"k": KEY, "amf": "8000", "op": None, "opc": OPC, "sqn": 0},
            "ambr": ambr,
            "slice": [{"sst": 1, "default_indicator": True,
                       "session": [{"name": f"d{k}{u}{s}", "type": 3, "qos": qos,
                                    "ambr": ambr, "pcc_rule": []} for s in SESSIONS]}],
            "__v": 0})
    js = f"""db = db.getSiblingDB("open5gs");
    let n = 0;
    for (const d of {json.dumps(docs)}) {{
      db.subscribers.replaceOne({{imsi: d.imsi}}, d, {{upsert: true}}); n++;
    }}
    print(n);"""
    with tempfile.NamedTemporaryFile("w", suffix=".js", delete=False) as f:
        f.write(js)
    try:
        r = subprocess.run(["mongosh", "--quiet", f.name], capture_output=True, text=True)
    finally:
        os.unlink(f.name)
    if r.returncode:
        sys.exit(f"mongosh failed:\n{r.stderr or r.stdout}")
    return r.stdout.strip()


# ── processes ────────────────────────────────────────────────────────────────
def pids() -> dict[str, int]:
    """Running NFs of this project, found by their config path."""
    out = {}
    for p in os.listdir("/proc"):
        if p.isdigit():
            try:
                args = open(f"/proc/{p}/cmdline", "rb").read().split(b"\0")
            except OSError:
                continue
            if len(args) > 2 and args[2].decode(errors="replace").startswith(CONF + os.sep):
                out[os.path.basename(args[2].decode())[:-5]] = int(p)
    return out


def rss_mb(pid: int) -> float:
    try:
        for line in open(f"/proc/{pid}/status"):
            if line.startswith("VmRSS"):
                return int(line.split()[1]) / 1024
    except OSError:
        pass
    return 0.0


def nrf_registered(kind: str) -> set[str]:
    """IPv4 addresses of the instances of one NF type the NRF holds as REGISTERED."""
    def get(path):
        r = subprocess.run(["curl", "-s", "--http2-prior-knowledge", "--max-time", "3",
                            NRF + path], capture_output=True, text=True)
        try:
            return json.loads(r.stdout)
        except ValueError:
            return {}
    out = set()
    for it in get(f"/nnrf-nfm/v1/nf-instances?nf-type={kind.upper()}&limit=500") \
            .get("_links", {}).get("item", []):
        prof = get("/nnrf-nfm/v1/nf-instances/" + it["href"].rsplit("/", 1)[-1])
        if prof.get("nfStatus") == "REGISTERED":
            out.update(prof.get("ipv4Addresses") or [])
    return out


def trim_logs() -> None:
    """Empty the NF log files (Open5GS appends to them: a long run writes gigabytes)."""
    for x in NFS:
        path = os.path.join(LOGS, f"{name(x)}.log")
        if os.path.exists(path):
            os.truncate(path, 0)


def log_count(x: Node, text: str) -> int:
    try:
        return open(os.path.join(LOGS, f"{name(x)}.log"), errors="replace").read().count(text)
    except OSError:
        return 0


def occupancy() -> dict[str, float]:
    """UEs (AMF) or sessions (SMF, UPF) each NF holds now, from its metrics page."""
    out = {}
    for x in NFS:
        try:
            body = urllib.request.urlopen(f"http://{addr(x)}:9090/metrics", timeout=3).read().decode()
            out[x.id] = next(float(l.split()[1]) for l in body.splitlines()
                             if l.startswith(GAUGE[x.kind] + " "))
        except Exception:
            out[x.id] = float("nan")
    return out


def preflight() -> None:
    bad = [u for u in STOCK
           if subprocess.run(["systemctl", "is-active", "--quiet", u]).returncode == 0]
    missing = [tun(x) for x in of_kind("upf") if not os.path.exists(f"/sys/class/net/{tun(x)}")]
    if bad or missing:
        sys.exit(f"not ready: stock NFs running {bad}, {len(missing)} UPF device(s) missing\n"
                 f"  run:  sudo {HERE}/setup.sh")


def wait(what: str, done, timeout: float = 90.0) -> None:
    end = time.time() + timeout
    while time.time() < end:
        left = done()
        if not left:
            print(f"  ok    {what}")
            return
        time.sleep(1.0)
    sys.exit(f"  FAIL  {what}: still waiting for {sorted(left)[:6]} ...")


def start() -> None:
    generate()
    preflight()
    if pids():
        sys.exit("already running -- python3 core.py stop first")
    print(f"  ok    {provision()} subscribers")
    for kind in ("upf", "smf", "amf"):        # an AMF reads the SMF list once, at start
        group = of_kind(kind)
        for x in group:
            log = os.path.join(LOGS, f"{name(x)}.log")
            if os.path.exists(log):
                os.remove(log)
            subprocess.Popen([BIN[kind], "-c", cfg(x)], stdout=subprocess.DEVNULL,
                             stderr=subprocess.DEVNULL, start_new_session=True)
            time.sleep(0.05)
        wait(f"{len(group)} {kind.upper()} processes up",
             lambda: {name(x) for x in group} - set(pids()), 20)
        if kind == "smf":
            wait("every SMF associated with its 2 UPFs (PFCP)",
                 lambda: {x.id for x in group if log_count(x, "PFCP associated") < N_UPF})
        if kind != "upf":
            wait(f"{len(group)} {kind.upper()} registered in the NRF",
                 lambda: {addr(x) for x in group} - nrf_registered(kind))
    time.sleep(3.0)                            # AMFs finish discovering UDM / AUSF
    status()


def stop() -> None:
    for sig in (signal.SIGTERM, signal.SIGKILL):
        for pid in pids().values():
            try:
                os.kill(pid, sig)
            except ProcessLookupError:
                pass
        end = time.time() + 10
        while pids() and time.time() < end:
            time.sleep(0.3)
    print(f"stopped ({len(pids())} left)")


def status() -> None:
    run = pids()
    reg = {k: nrf_registered(k) for k in ("amf", "smf")}
    print(f"\n{'platform':9} {'AMF':>5} {'SMF':>5} {'UPF':>5}   registered AMF/SMF   memory")
    for n, p in enumerate(PLATFORMS, 1):
        mine = [x for x in NFS if x.n == n]
        up = {k: sum(name(x) in run for x in mine if x.kind == k) for k in BIN}
        tot = {k: sum(x.kind == k for x in mine) for k in BIN}
        r = {k: sum(addr(x) in reg[k] for x in mine if x.kind == k) for k in reg}
        mem = sum(rss_mb(run[name(x)]) for x in mine if name(x) in run)
        print(f"{p:9} " + " ".join(f"{up[k]}/{tot[k]:<3}" for k in BIN)
              + f"   {r['amf']}/{tot['amf']}  {r['smf']}/{tot['smf']:<10}   {mem:6.0f} MB")
    print(f"total     {len(run)}/{len(NFS)} processes, "
          f"{sum(rss_mb(p) for p in run.values()):.0f} MB")
    crashed = [x.id for x in NFS if log_count(x, "FATAL") or log_count(x, "Assertion")]
    if crashed:
        print(f"errors in the log of: {crashed}")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "status"
    {"start": start, "stop": stop, "status": status}.get(
        cmd, lambda: sys.exit(__doc__))()
