"""
Step 2b -- the UERANSIM_XN side: gNBs, UEs and the Xn handover primitive.

The model has one gNB per platform. The modified UERANSIM sends the Path Switch
to the gNB's first connected AMF, so behind each platform gNB there is one
source and one target gNB process per AMF: 8 AMFs -> 16 gNB processes. The
source gNB plays the serving satellite, the target gNB the target platform.

A gNB numbers the UEs it hears in the order they appear, and keeps that number
for good. UEs are therefore started one at a time, with both gNBs already up:
that gives every UE a known id on each gNB, so one chosen UE can be handed
over, back and forth, as often as needed.

Used by check_paths.py and executor.py; nothing to run here.
"""
