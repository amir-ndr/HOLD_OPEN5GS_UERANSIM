# ── configs ──────────────────────────────────────────────────────────────────
def gnb(amf: Node, target: bool) -> dict:
    """Identity of the source or target gNB process of one AMF."""
    g = core.amf_index(amf)
    nci = (g + 17 if target else g + 1) * 16          # <= 1007: it is sent as physCellId
    return {"name": f"{core.name(amf)}-{'tgt' if target else 'src'}", "nci": nci,
            "ip": f"127.0.30.{(21 if target else 1) + g}",
            "cli": f"UERANSIM-gnb-{core.MCC}-{core.MNC}-{nci >> 4}"}


