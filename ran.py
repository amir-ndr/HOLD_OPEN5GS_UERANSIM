# ── processes and the CLI ────────────────────────────────────────────────────
class Proc:
    """One nr-gnb or nr-ue process with its log file."""

    def __init__(self, name: str, binary: str, yaml: str):
        os.makedirs(CONF, exist_ok=True)
        os.makedirs(LOGS, exist_ok=True)
        os.makedirs("/tmp/UERANSIM.proc-table", exist_ok=True)   # two processes starting at once
                                                                 # after a reboot fail to create it
        cfg = os.path.join(CONF, f"{name}.yaml")
        with open(cfg, "w") as f:
            f.write(yaml)
        self.name = name
        self.log = os.path.join(LOGS, f"{name}.log")
        open(self.log, "w").close()
        self.fh = open(self.log, "a")              # appending, so trim() really frees the space
        self.pos = 0                               # how far fresh() has read
        self.p = subprocess.Popen([os.path.join(BUILD, binary), "-c", cfg], stdout=self.fh,
                                  stderr=subprocess.STDOUT, start_new_session=True)

    def text(self) -> str:
        return ANSI.sub("", open(self.log, errors="replace").read())

    def fresh(self) -> str:
        """The complete log lines written since the last call."""
        with open(self.log, "rb") as f:
            f.seek(self.pos)
            data = f.read()
        data = data[:data.rfind(b"\n") + 1]
        self.pos += len(data)
        return ANSI.sub("", data.decode(errors="replace"))

    def wait(self, pattern: str, count: int = 1, timeout: float = 30.0) -> None:
        end = time.time() + timeout
        while time.time() < end:
            seen = len(re.findall(pattern, self.text()))
            if seen >= count:
                return
            if self.p.poll() is not None:
                break
            time.sleep(0.2)
        raise TimeoutError(f"{self.name}: '{pattern}' seen {seen}/{count}\n" + self.text()[-1200:])

    def trim(self) -> None:
        """Empty the log file (everything read so far is no longer needed)."""
        os.truncate(self.log, 0)
        self.pos = 0

    def stop(self) -> None:
        if self.p.poll() is None:
            self.p.send_signal(signal.SIGTERM)
            try:
                self.p.wait(timeout=5)
            except subprocess.TimeoutExpired:
                self.p.kill()
        self.fh.close()


_sock, _ports = None, {}                 # CLI socket; node name -> its CLI port


def cli(node: str, command: str) -> str:
    """Send one command over the UERANSIM CLI's UDP socket (no nr-cli spawn)."""
    global _sock
    if _sock is None:
        _sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        _sock.settimeout(3.0)
        _sock.bind(("127.0.0.1", 0))
    if node not in _ports:
        for path in glob.glob("/tmp/UERANSIM.proc-table/*"):    # written by each live process
            try:
                parts = open(path).read().split()
                if os.path.exists(f"/proc/{parts[3]}"):
                    for n in parts[6:6 + int(parts[5])]:
                        _ports[n] = int(parts[4])
            except (OSError, IndexError, ValueError):
                continue
    if node not in _ports:
        raise RuntimeError(f"no live UERANSIM node named {node}")
    n, v = node.encode(), command.encode()
    _sock.sendto(bytes([3, 2, 7, 4]) + struct.pack(">I", len(n)) + n
                 + struct.pack(">I", len(v)) + v, ("127.0.0.1", _ports[node]))
    data, _ = _sock.recvfrom(65535)
    off = 8 + struct.unpack_from(">I", data, 4)[0]
    return data[off + 4:off + 4 + struct.unpack_from(">I", data, off)[0]].decode(errors="replace")


def kill_stray() -> None:
    """Kill every nr-gnb / nr-ue left over from an earlier run."""
    for p in os.listdir("/proc"):
        try:
            if p.isdigit() and os.path.basename(os.readlink(f"/proc/{p}/exe")) in ("nr-gnb", "nr-ue"):
                os.kill(int(p), signal.SIGKILL)
        except OSError:
            pass
    _ports.clear()


# ── one AMF's radio side ─────────────────────────────────────────────────────
class Ran:
    """The source and target gNB of one AMF and the UEs attached through them."""

    def __init__(self, amf: Node):
        self.amf = amf
        self.gnbs: dict[bool, Proc] = {}             # target? -> process
        self.ues: dict[int, Proc] = {}               # subscriber -> process
        self.sessions: dict[int, int] = {}           # subscriber -> its PDU sessions
        self.ids: dict[int, dict[bool, int]] = {}    # subscriber -> its UE id on each gNB
        self.at: dict[int, bool] = {}                # subscriber -> the gNB serving it (target?)
        self.moving: dict[tuple[bool, int], int] = {}   # handovers in flight: (gNB, id) -> subscriber

    def start_gnbs(self) -> None:
        for target in (False, True):
            self.gnbs[target] = Proc(gnb(self.amf, target)["name"], "nr-gnb", gnb_yaml(self.amf, target))
        for p in self.gnbs.values():
            p.wait("NG Setup procedure is successful", timeout=20)

    def add_ue(self, sub: int, n_sessions: int) -> None:
        """Start one UE and wait until both gNBs hear it: that fixes its id on each."""
        self.ues[sub] = Proc(f"ue{sub}", "nr-ue", ue_yaml(sub, self.amf, n_sessions))
        self.sessions[sub] = n_sessions
        self.ids[sub] = {}
        for target, p in self.gnbs.items():
            p.wait(SEEN.pattern, count=len(self.ues), timeout=20)
            self.ids[sub][target] = int(SEEN.findall(p.text())[-1])

    def wait_attached(self, timeout: float = 90.0) -> None:
        """Wait for every PDU session, then find the gNB each UE chose."""
        for sub, ue in self.ues.items():
            ue.wait("PDU Session establishment is successful", count=self.sessions[sub], timeout=timeout)
        for target in self.gnbs:
            here = {int(i) for i in re.findall(r"ue-id:\s*(\d+)", cli(gnb(self.amf, target)["cli"], "ue-list"))}
            self.at.update({sub: target for sub, ids in self.ids.items() if ids[target] in here})
        if len(self.at) != len(self.ues):
            raise RuntimeError(f"{self.amf.id}: {len(self.ues) - len(self.at)} UE(s) on no gNB")

    def trigger(self, sub: int) -> None:
        """Start the Xn handover of one UE to its other gNB."""
        here = self.at.pop(sub)
        out = cli(gnb(self.amf, here)["cli"],
                  f"xn-handover {self.ids[sub][here]} {gnb(self.amf, not here)['ip']}")
        if "triggered" not in out.lower():
            raise RuntimeError(f"ue{sub}: handover refused: {out}")
        self.moving[not here, self.ids[sub][not here]] = sub

    def completed(self) -> dict[int, dict]:
        """Handovers that finished since the last call: subscriber -> result."""
        out = {}
        for target, p in self.gnbs.items():
            for m in DONE.finditer(p.fresh()):
                sub = self.moving.pop((target, int(m[1])))
                self.at[sub] = target
                out[sub] = {"sessions": int(m[2]), "arrival_ms": float(m[3]),
                            "psw_ms": float(m[4]), "total_ms": float(m[5])}
        return out

    def close(self) -> None:
        # Deregister through a live cell, or the SMF and UPF keep the sessions.
        # "disable-5g", not "normal": after a normal one the UE registers again
        # at once and opens new sessions, which are then orphaned by the kill.
        for sub in self.ues:
            try:
                cli(f"imsi-{core.imsi(sub)}", "deregister disable-5g")
            except Exception:
                pass
        for ue in self.ues.values():
            try:
                ue.wait("De-registration is successful", timeout=10)
            except TimeoutError:
                pass
        for p in list(self.ues.values()) + list(self.gnbs.values()):
            p.stop()


def finish(rans: list[Ran], timeout: float = 30.0) -> dict[int, dict]:
    """Wait until every triggered handover of these Rans has completed."""
    out, end = {}, time.time() + timeout
    while True:
        for r in rans:
            out.update(r.completed())
        stuck = [f"ue{sub}" for r in rans for sub in r.moving.values()]
        if not stuck:
            return out
        if time.time() > end:
            raise TimeoutError(f"handover not completed: {' '.join(stuck)}")
        time.sleep(0.005)
